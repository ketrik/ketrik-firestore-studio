import * as vscode from "vscode";
import { CollectionItem, DocumentItem } from "../explorer/items";
import { ConnectionManager } from "../connections/ConnectionManager";

export interface InferredField {
  name: string;
  types: Set<string>;
  optional: boolean;
  stringValues: Set<string>; // For enum inference
  nestedFields?: Map<string, InferredField>;
  arrayElementTypes?: Set<string>;
}

/**
 * Infer field structure and data types from a set of sampled Firestore documents.
 */
export function inferCollectionSchema(documents: Record<string, any>[]): Map<string, InferredField> {
  const schema = new Map<string, InferredField>();
  const totalDocs = documents.length;
  if (totalDocs === 0) {
    return schema;
  }

  const fieldCounts = new Map<string, number>();

  for (const doc of documents) {
    for (const [key, val] of Object.entries(doc)) {
      if (key === "__path" || key === "__id") {
        continue;
      }
      fieldCounts.set(key, (fieldCounts.get(key) || 0) + 1);

      let field = schema.get(key);
      if (!field) {
        field = {
          name: key,
          types: new Set<string>(),
          optional: false,
          stringValues: new Set<string>(),
        };
        schema.set(key, field);
      }

      const inferredType = detectValueType(val);
      field.types.add(inferredType);

      if (inferredType === "string" && typeof val === "string" && val.length < 50) {
        field.stringValues.add(val);
      }

      if (inferredType === "object" && val && typeof val === "object" && !Array.isArray(val)) {
        if (!field.nestedFields) {
          field.nestedFields = new Map<string, InferredField>();
        }
        const subSchema = inferCollectionSchema([val]);
        for (const [subKey, subField] of subSchema.entries()) {
          const existingSub = field.nestedFields.get(subKey);
          if (!existingSub) {
            field.nestedFields.set(subKey, subField);
          } else {
            subField.types.forEach((t) => existingSub.types.add(t));
          }
        }
      }

      if (inferredType === "array" && Array.isArray(val)) {
        if (!field.arrayElementTypes) {
          field.arrayElementTypes = new Set<string>();
        }
        for (const item of val) {
          field.arrayElementTypes.add(detectValueType(item));
        }
      }
    }
  }

  // Determine optional status (if absent in any sampled doc or contains null)
  for (const [key, field] of schema.entries()) {
    const count = fieldCounts.get(key) || 0;
    if (count < totalDocs || field.types.has("null")) {
      field.optional = true;
    }
  }

  return schema;
}

function detectValueType(val: any): string {
  if (val === null || val === undefined) {
    return "null";
  }
  if (typeof val === "boolean") {
    return "boolean";
  }
  if (typeof val === "number") {
    return "number";
  }
  if (typeof val === "string") {
    return "string";
  }
  if (Array.isArray(val)) {
    return "array";
  }
  if (typeof val === "object") {
    // Firestore Timestamp
    if (val._seconds !== undefined && val._nanoseconds !== undefined) {
      return "Timestamp";
    }
    // Firestore GeoPoint
    if (val._latitude !== undefined && val._longitude !== undefined) {
      return "GeoPoint";
    }
    // Firestore DocumentReference
    if (val.path && typeof val.path === "string" && val.firestore) {
      return "DocumentReference";
    }
    return "object";
  }
  return "unknown";
}

/**
 * Format a PascalCase interface name from a collection ID.
 */
function toPascalCase(str: string): string {
  return str
    .replace(/[^a-zA-Z0-9]+(.)/g, (_, chr) => chr.toUpperCase())
    .replace(/^[a-z]/, (chr) => chr.toUpperCase());
}

/**
 * Generate TypeScript Interface definitions.
 */
export function generateTypeScriptCode(
  collectionName: string,
  schema: Map<string, InferredField>,
  sampleCount: number
): string {
  const interfaceName = `${toPascalCase(collectionName)}Doc`;
  const lines: string[] = [];

  lines.push("/**");
  lines.push(` * TypeScript interface for Firestore collection: ${collectionName}`);
  lines.push(` * Inferred from a representative sample of ${sampleCount} document(s).`);
  lines.push(` * Generated by Ketrik Firestore Studio`);
  lines.push(" */");
  lines.push(`export interface ${interfaceName} {`);
  lines.push(`  /** Firestore Document ID */`);
  lines.push(`  id?: string;`);

  for (const field of schema.values()) {
    const isOptional = field.optional ? "?" : "";
    let typeStr = "any";

    // Handle enums if small set of distinct strings
    if (field.types.has("string") && field.types.size === 1 && field.stringValues.size > 1 && field.stringValues.size <= 5) {
      typeStr = Array.from(field.stringValues).map((v) => JSON.stringify(v)).join(" | ");
    } else {
      const concreteTypes = Array.from(field.types).filter((t) => t !== "null");
      if (concreteTypes.length === 0) {
        typeStr = "null";
      } else {
        typeStr = concreteTypes
          .map((t) => {
            if (t === "Timestamp") return "FirebaseFirestore.Timestamp | Date";
            if (t === "GeoPoint") return "FirebaseFirestore.GeoPoint";
            if (t === "DocumentReference") return "FirebaseFirestore.DocumentReference";
            if (t === "array") {
              const elTypes = field.arrayElementTypes ? Array.from(field.arrayElementTypes) : ["any"];
              return elTypes.length === 1 ? `${elTypes[0]}[]` : `(${elTypes.join(" | ")})[]`;
            }
            if (t === "object") {
              if (field.nestedFields && field.nestedFields.size > 0) {
                const subProps = Array.from(field.nestedFields.values())
                  .map((sub) => `${sub.name}${sub.optional ? "?" : ""}: ${Array.from(sub.types).join(" | ")}`)
                  .join("; ");
                return `{ ${subProps} }`;
              }
              return "Record<string, any>";
            }
            return t;
          })
          .join(" | ");
      }
    }

    if (field.types.has("null") && !typeStr.includes("null")) {
      typeStr += " | null";
    }

    lines.push(`  ${field.name}${isOptional}: ${typeStr};`);
  }

  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

/**
 * Generate Zod Schema definitions.
 */
export function generateZodCode(
  collectionName: string,
  schema: Map<string, InferredField>,
  sampleCount: number
): string {
  const schemaName = `${toPascalCase(collectionName)}Schema`;
  const typeName = `${toPascalCase(collectionName)}Doc`;
  const lines: string[] = [];

  lines.push(`import { z } from "zod";`);
  lines.push("");
  lines.push("/**");
  lines.push(` * Zod validation schema for Firestore collection: ${collectionName}`);
  lines.push(` * Inferred from a sample of ${sampleCount} document(s).`);
  lines.push(` * Generated by Ketrik Firestore Studio`);
  lines.push(" */");
  lines.push(`export const ${schemaName} = z.object({`);
  lines.push(`  id: z.string().optional(),`);

  for (const field of schema.values()) {
    let zodType = "z.any()";

    if (field.types.has("string") && field.types.size === 1 && field.stringValues.size > 1 && field.stringValues.size <= 5) {
      const vals = Array.from(field.stringValues).map((v) => JSON.stringify(v)).join(", ");
      zodType = `z.enum([${vals}])`;
    } else {
      const concreteTypes = Array.from(field.types).filter((t) => t !== "null");
      if (concreteTypes.length === 1) {
        const t = concreteTypes[0];
        if (t === "string") zodType = "z.string()";
        else if (t === "number") zodType = "z.number()";
        else if (t === "boolean") zodType = "z.boolean()";
        else if (t === "Timestamp") zodType = "z.union([z.date(), z.custom<any>()])";
        else if (t === "GeoPoint") zodType = "z.custom<any>()";
        else if (t === "DocumentReference") zodType = "z.custom<any>()";
        else if (t === "array") {
          const elTypes = field.arrayElementTypes ? Array.from(field.arrayElementTypes) : ["any"];
          zodType = elTypes.length === 1 && elTypes[0] !== "any" ? `z.array(z.${elTypes[0]}())` : "z.array(z.any())";
        } else if (t === "object") {
          zodType = "z.record(z.string(), z.any())";
        }
      } else if (concreteTypes.length > 1) {
        const unionArgs = concreteTypes.map((t) => `z.${t}()`).join(", ");
        zodType = `z.union([${unionArgs}])`;
      }
    }

    if (field.types.has("null")) {
      zodType += ".nullable()";
    }
    if (field.optional) {
      zodType += ".optional()";
    }

    lines.push(`  ${field.name}: ${zodType},`);
  }

  lines.push("});");
  lines.push("");
  lines.push(`export type ${typeName} = z.infer<typeof ${schemaName}>;`);
  lines.push("");
  return lines.join("\n");
}

/**
 * Command: Generate TypeScript / Zod Schemas for a Collection or Document.
 */
export async function generateSchemaCommand(item?: CollectionItem | DocumentItem) {
  let connectionId: string;
  let collectionPath: string;
  let collectionName: string;
  let isSingleDoc = false;

  if (item instanceof CollectionItem) {
    connectionId = item.connectionId;
    collectionPath = item.reference.path;
    collectionName = item.collectionId;
  } else if (item instanceof DocumentItem) {
    connectionId = item.connectionId;
    collectionPath = item.reference.parent.path;
    collectionName = item.reference.parent.id;
    isSingleDoc = true;
  } else {
    vscode.window.showErrorMessage("Please select a Firestore collection or document to generate schemas.");
    return;
  }

  // 1. Choose target format
  const formatChoice = await vscode.window.showQuickPick(
    [
      { label: "$(symbol-interface) TypeScript Interface", detail: "Generate export interface <Name>Doc with optional fields & types", format: "ts" },
      { label: "$(shield) Zod Schema", detail: "Generate export const <Name>Schema = z.object(...) with runtime validations", format: "zod" },
    ],
    { title: `Generate Schema for '${collectionName}'`, placeHolder: "Select schema generation target" }
  );

  if (!formatChoice) {
    return;
  }

  // 2. Choose sample size (if not a single document)
  let sampleSize = 25;
  if (!isSingleDoc) {
    const sampleChoice = await vscode.window.showQuickPick(
      [
        { label: "25 documents (Recommended)", size: 25 },
        { label: "10 documents (Fastest)", size: 10 },
        { label: "50 documents (High accuracy)", size: 50 },
        { label: "100 documents (Comprehensive)", size: 100 },
      ],
      { title: "Select Document Sampling Size", placeHolder: "Higher sampling improves optional field & enum detection" }
    );
    if (!sampleChoice) {
      return;
    }
    sampleSize = sampleChoice.size;
  }

  // 3. Fetch sampled documents
  let sampleDocs: Record<string, any>[] = [];
  await vscode.window.withProgress(
    {
      location: vscode.ProgressLocation.Notification,
      title: `Analyzing documents in '${collectionName}'...`,
      cancellable: false,
    },
    async () => {
      try {
        const firestore = await ConnectionManager.getInstance().getFirestore(connectionId);
        if (isSingleDoc && item instanceof DocumentItem) {
          const snapshot = await item.reference.get();
          if (snapshot.exists && snapshot.data()) {
            sampleDocs.push(snapshot.data()!);
          }
        } else {
          const snapshot = await firestore.collection(collectionPath).limit(sampleSize).get();
          snapshot.docs.forEach((doc) => {
            if (doc.exists) {
              sampleDocs.push(doc.data());
            }
          });
        }
      } catch (err: any) {
        vscode.window.showErrorMessage(`Failed to sample collection '${collectionName}': ${err.message}`);
      }
    }
  );

  if (sampleDocs.length === 0) {
    vscode.window.showWarningMessage(`Collection '${collectionName}' has no documents to sample.`);
    return;
  }

  // 4. Infer Schema
  const schema = inferCollectionSchema(sampleDocs);
  let code = "";
  let extension = "ts";

  if (formatChoice.format === "ts") {
    code = generateTypeScriptCode(collectionName, schema, sampleDocs.length);
    extension = "d.ts";
  } else {
    code = generateZodCode(collectionName, schema, sampleDocs.length);
    extension = "ts";
  }

  // 5. Destination option
  const destChoice = await vscode.window.showQuickPick(
    [
      { label: "$(copy) Copy to Clipboard", action: "copy" },
      { label: "$(file-code) Open in New Editor Tab", action: "editor" },
      { label: "$(save) Save to Workspace File...", action: "save" },
    ],
    { title: "Schema Generated Successfully!", placeHolder: "How would you like to use the generated code?" }
  );

  if (!destChoice) {
    return;
  }

  if (destChoice.action === "copy") {
    await vscode.env.clipboard.writeText(code);
    vscode.window.showInformationMessage(`Generated schema for '${collectionName}' copied to clipboard!`);
  } else if (destChoice.action === "editor") {
    const doc = await vscode.workspace.openTextDocument({
      language: "typescript",
      content: code,
    });
    await vscode.window.showTextDocument(doc);
  } else if (destChoice.action === "save") {
    const suggestedFileName = `${collectionName}.${extension}`;
    const uri = await vscode.window.showSaveDialog({
      defaultUri: vscode.Uri.file(suggestedFileName),
      filters: { TypeScript: [extension.replace(".", ""), "ts"] },
    });
    if (uri) {
      await vscode.workspace.fs.writeFile(uri, Buffer.from(code, "utf8"));
      vscode.window.showInformationMessage(`Schema saved to ${uri.fsPath}!`);
      const doc = await vscode.workspace.openTextDocument(uri);
      await vscode.window.showTextDocument(doc);
    }
  }
}
